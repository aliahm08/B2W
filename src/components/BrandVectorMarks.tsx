type VectorMarkProps = {
  className?: string;
  title?: string;
  animated?: boolean;
  strokeWidth?: number;
};

function VectorPathSet({
  paths,
  animated = true,
  strokeWidth = 2.7,
}: {
  paths: readonly string[];
  animated?: boolean;
  strokeWidth?: number;
}) {
  const duration = paths.length > 15 ? 5.8 : 5;
  const delayStep = paths.length > 15 ? 0.16 : 0.18;

  return (
    <>
      {paths.map((path, index) => {
        const style = animated
          ? ({
              animationDelay: `${index * delayStep}s`,
              animationDuration: `${duration}s`,
            } as CSSProperties)
          : undefined;

        return (
          <path
            key={path}
            d={path}
            fill="none"
            stroke="currentColor"
            strokeLinecap="round"
            strokeLinejoin="round"
            strokeWidth={strokeWidth}
            vectorEffect="non-scaling-stroke"
            className={animated ? 'b2w-logo-layer' : undefined}
            style={style}
          />
        );
      })}
    </>
  );
}

export function B2WVectorMark({ className = '', title = 'B2W vector mark', animated = true, strokeWidth = 2.7 }: VectorMarkProps) {
  return (
    <svg viewBox="0 0 96 96" className={className} role={title ? 'img' : undefined} aria-hidden={title ? undefined : true}>
      {title ? <title>{title}</title> : null}
      <VectorPathSet paths={b2wVectorPaths} animated={animated} strokeWidth={strokeWidth} />
    </svg>
  );
}

